"""
PDF export service.

Generation strategy (in order):
  1. weasyprint (HTML → PDF) — best quality, needs system libs
  2. reportlab   (pure Python PDF writer) — always available
  3. Raise RuntimeError — never return HTML bytes as PDF

NEVER falls back to returning HTML bytes with application/pdf Content-Type.
That produces a "damaged/unsupported" file in Adobe Reader.
"""
from __future__ import annotations
import io
from typing import Optional


def _try_weasyprint(html: str) -> Optional[bytes]:
    try:
        import weasyprint                               # type: ignore
        return weasyprint.HTML(string=html).write_pdf()
    except Exception:
        return None


def _build_reportlab_pdf(company_id: str, data: dict) -> bytes:
    """
    Pure-Python fallback using reportlab.
    Produces a valid, well-formed PDF regardless of system dependencies.
    """
    from reportlab.lib.pagesizes import A4              # type: ignore
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.lib import colors
    from reportlab.platypus import (                    # type: ignore
        SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
    )

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=20*mm, rightMargin=20*mm,
        topMargin=20*mm, bottomMargin=20*mm
    )

    styles = getSampleStyleSheet()
    NAVY   = colors.HexColor("#0B2545")
    TEAL   = colors.HexColor("#0D9488")
    GREY   = colors.HexColor("#64748B")
    GREEN  = colors.HexColor("#059669")
    AMBER  = colors.HexColor("#D97706")
    RED    = colors.HexColor("#DC2626")

    title_style = ParagraphStyle("Title", parent=styles["Title"],
        textColor=NAVY, fontSize=18, spaceAfter=4)
    h2_style = ParagraphStyle("H2", parent=styles["Heading2"],
        textColor=NAVY, fontSize=13, spaceBefore=12, spaceAfter=4)
    body_style = ParagraphStyle("Body", parent=styles["Normal"],
        textColor=GREY, fontSize=9, spaceAfter=2)

    kpis  = data.get("kpis", {})
    years = data.get("years", [])
    cost  = data.get("cost_structure", [])

    def fmt(v, pct=False):
        if v is None: return "N/A"
        return f"{v:.1f}%" if pct else f"{v:,.0f}"

    def to_cr(v):
        """Convert INR Mn → Cr and format with commas."""
        if v is None: return "N/A"
        return f"{v/10:,.0f}"

    def safe_cr(key, sub="value"):
        return to_cr((kpis.get(key) or {}).get(sub))

    def safe_pct(key, sub="margin"):
        v = (kpis.get(key) or {}).get(sub)
        return fmt(v, pct=True) if v is not None else "N/A"

    z_val  = (kpis.get("altman_z") or {}).get("value")
    z_zone = (kpis.get("altman_z") or {}).get("zone", "")
    z_color = GREEN if z_zone == "safe" else (AMBER if z_zone == "grey" else RED)

    story = []

    # ── Title ──────────────────────────────────────────────────────
    story.append(Paragraph(f"Financial Analytics Report — {company_id}", title_style))
    story.append(HRFlowable(width="100%", thickness=2, color=TEAL))
    story.append(Paragraph(
        f"Period: {years[0] if years else 'N/A'}  |  Generated by FinIntel Platform v2.0",
        body_style
    ))
    story.append(Spacer(1, 6*mm))

    # ── KPI Table ─────────────────────────────────────────────────
    story.append(Paragraph("Key Financial Metrics", h2_style))

    kpi_data = [
        ["Metric", "Value (INR Cr)", "Margin / YoY"],
        ["Revenue from Operations", safe_cr("revenue"),       safe_pct("revenue", "yoy")+" YoY"],
        ["EBITDA",                  safe_cr("ebitda"),        safe_pct("ebitda")+" Margin"],
        ["EBIT",                    safe_cr("ebit"),          safe_pct("ebit")+" Margin"],
        ["PAT",                     safe_cr("pat"),           safe_pct("pat")+" Margin"],
        ["Total Assets",            safe_cr("total_assets"),  ""],
        ["Net Worth",               safe_cr("net_worth"),     ""],
        ["Working Capital",         safe_cr("working_capital"),""],
        ["Current Ratio",           fmt((kpis.get("current_ratio") or {}).get("value")), ""],
        ["ROE",                     fmt((kpis.get("roe") or {}).get("value"), pct=True), ""],
    ]

    kpi_table = Table(kpi_data, colWidths=[70*mm, 50*mm, 50*mm])
    kpi_table.setStyle(TableStyle([
        ("BACKGROUND",    (0,0), (-1,0),  NAVY),
        ("TEXTCOLOR",     (0,0), (-1,0),  colors.white),
        ("FONTNAME",      (0,0), (-1,0),  "Helvetica-Bold"),
        ("FONTSIZE",      (0,0), (-1,-1), 9),
        ("ROWBACKGROUNDS",(0,1), (-1,-1), [colors.HexColor("#F8FAFC"), colors.white]),
        ("GRID",          (0,0), (-1,-1), 0.4, colors.HexColor("#E2E8F0")),
        ("TOPPADDING",    (0,0), (-1,-1), 4),
        ("BOTTOMPADDING", (0,0), (-1,-1), 4),
        ("LEFTPADDING",   (0,0), (-1,-1), 6),
    ]))
    story.append(kpi_table)
    story.append(Spacer(1, 6*mm))

    # ── Altman Z ──────────────────────────────────────────────────
    story.append(Paragraph("Altman Z-Score", h2_style))

    z_display = f"{z_val:.2f}" if z_val is not None else "N/A"
    z_label   = z_zone.upper() if z_zone else "N/A"
    z_data = [
        ["Z Score", "Zone", "Interpretation"],
        [z_display, z_label,
         "Low bankruptcy risk" if z_zone=="safe"
         else ("Moderate risk — monitor" if z_zone=="grey"
               else "High bankruptcy risk")],
    ]
    z_table = Table(z_data, colWidths=[40*mm, 40*mm, 90*mm])
    z_table.setStyle(TableStyle([
        ("BACKGROUND",   (0,0), (-1,0), NAVY),
        ("TEXTCOLOR",    (0,0), (-1,0), colors.white),
        ("FONTNAME",     (0,0), (-1,0), "Helvetica-Bold"),
        ("FONTSIZE",     (0,0), (-1,-1), 9),
        ("TEXTCOLOR",    (1,1), (1,1),  z_color),
        ("FONTNAME",     (1,1), (1,1),  "Helvetica-Bold"),
        ("GRID",         (0,0), (-1,-1), 0.4, colors.HexColor("#E2E8F0")),
        ("TOPPADDING",   (0,0), (-1,-1), 4),
        ("BOTTOMPADDING",(0,0), (-1,-1), 4),
        ("LEFTPADDING",  (0,0), (-1,-1), 6),
    ]))
    story.append(z_table)
    story.append(Spacer(1, 6*mm))

    # ── Cost Structure ────────────────────────────────────────────
    if cost:
        story.append(Paragraph("Cost Structure (INR Cr)", h2_style))
        rev_mn   = (kpis.get("revenue") or {}).get("value")   # INR Mn
        total_mn = sum(c["value"] for c in cost if c.get("value"))
        pbt_mn   = (rev_mn - total_mn) if rev_mn else None
        cost_rows = [["Cost Item", "Value (INR Cr)", "% of Revenue"]]
        for c in sorted(cost, key=lambda x: -(x.get("value") or 0)):
            v = c.get("value")
            pct_s = f"{round(v / rev_mn * 100)}%" if (v and rev_mn) else "N/A"
            cost_rows.append([c["item"], to_cr(v), pct_s])
        if pbt_mn is not None:
            pbt_pct = f"{round(pbt_mn / rev_mn * 100)}%" if rev_mn else "N/A"
            cost_rows.append(["Operational PBT", to_cr(pbt_mn), pbt_pct])
        cost_rows.append(["TOTAL", to_cr(rev_mn), "100%"])

        c_table = Table(cost_rows, colWidths=[90*mm, 50*mm, 30*mm])
        c_table.setStyle(TableStyle([
            ("BACKGROUND",    (0,0), (-1,0),   NAVY),
            ("TEXTCOLOR",     (0,0), (-1,0),   colors.white),
            ("FONTNAME",      (0,0), (-1,0),   "Helvetica-Bold"),
            ("FONTNAME",      (0,-1),(-1,-1),  "Helvetica-Bold"),
            ("BACKGROUND",    (0,-1),(-1,-1),  colors.HexColor("#F1F5F9")),
            ("FONTSIZE",      (0,0), (-1,-1),  9),
            ("ROWBACKGROUNDS",(0,1), (-1,-2),  [colors.HexColor("#F8FAFC"), colors.white]),
            ("GRID",          (0,0), (-1,-1),  0.4, colors.HexColor("#E2E8F0")),
            ("TOPPADDING",    (0,0), (-1,-1),  4),
            ("BOTTOMPADDING", (0,0), (-1,-1),  4),
            ("LEFTPADDING",   (0,0), (-1,-1),  6),
        ]))
        story.append(c_table)

    # ── Footer ────────────────────────────────────────────────────
    story.append(Spacer(1, 10*mm))
    story.append(HRFlowable(width="100%", thickness=0.5, color=GREY))
    story.append(Paragraph(
        "FinIntel Financial Analytics Platform v2.0  —  Confidential",
        ParagraphStyle("Footer", parent=styles["Normal"],
            textColor=GREY, fontSize=8, spaceAfter=0)
    ))

    doc.build(story)
    return buf.getvalue()


def _validate_pdf(b: bytes) -> None:
    """Raise if bytes are not a valid PDF header."""
    if not b or not b.startswith(b"%PDF"):
        raise RuntimeError(
            f"Generated output is not a valid PDF "
            f"(starts with {b[:8]!r}, len={len(b)})"
        )


class PDFService:
    def __init__(self, svc):
        self.svc = svc

    def generate(self, company_id: str, period: str = None,
                 report_type: str = "consolidated") -> bytes:
        data = self.svc.get_dashboard_data(company_id, period=period,
                                           report_type=report_type)
        html = self._build_html(company_id, data)

        # Strategy 1: weasyprint
        pdf = _try_weasyprint(html)
        if pdf:
            _validate_pdf(pdf)
            return pdf

        # Strategy 2: reportlab (pure-Python, always available)
        try:
            import reportlab  # noqa — just checking availability
            pdf = _build_reportlab_pdf(company_id, data)
            _validate_pdf(pdf)
            return pdf
        except ImportError:
            pass

        # Strategy 3: fail loudly — NEVER send HTML as PDF
        raise RuntimeError(
            "PDF generation requires either 'weasyprint' or 'reportlab'. "
            "Install with: pip install reportlab"
        )

    def _build_html(self, company_id: str, data: dict) -> str:
        """HTML template used by weasyprint path."""
        kpis  = data.get("kpis", {})
        years = data.get("years", [])
        cost  = data.get("cost_structure", [])

        def fmt(v, pct=False):
            if v is None: return "—"
            return f"{v:.1f}%" if pct else f"{v:,.0f}"

        def to_cr(v):
            if v is None: return "—"
            return f"{v/10:,.0f}"

        rev = kpis.get("revenue", {})
        ebd = kpis.get("ebitda", {})
        pat = kpis.get("pat", {})
        z   = kpis.get("altman_z", {})
        z_color = ("#059669" if z.get("zone")=="safe"
                   else ("#D97706" if z.get("zone")=="grey" else "#DC2626"))

        rev_mn = rev.get("value")
        z_val  = z.get("value")
        z_disp = f"{z_val:.2f}" if z_val is not None else "—"

        cost_rows_html = ""
        if cost:
            total_mn = sum(c["value"] for c in cost if c.get("value"))
            pbt_mn   = (rev_mn - total_mn) if rev_mn else None
            for c in sorted(cost, key=lambda x: -(x.get("value") or 0)):
                v = c.get("value")
                pct_s = f"{round(v / rev_mn * 100)}%" if (v and rev_mn) else "—"
                cost_rows_html += f"<tr><td>{c['item']}</td><td>{to_cr(v)}</td><td>{pct_s}</td></tr>"
            if pbt_mn is not None:
                pbt_pct = f"{round(pbt_mn / rev_mn * 100)}%" if rev_mn else "—"
                cost_rows_html += f"<tr><td>Operational PBT</td><td>{to_cr(pbt_mn)}</td><td>{pbt_pct}</td></tr>"
            cost_rows_html += f"<tr style='font-weight:bold;background:#F1F5F9'><td>TOTAL</td><td>{to_cr(rev_mn)}</td><td>100%</td></tr>"

        return f"""<!DOCTYPE html><html><head>
<style>
  body {{font-family:Arial,sans-serif;padding:40px;color:#1E293B;}}
  h1 {{color:#0B2545;border-bottom:3px solid #0D9488;padding-bottom:8px;}}
  h2 {{color:#0B2545;margin-top:32px;}}
  table {{border-collapse:collapse;width:100%;margin:16px 0;}}
  th {{background:#0B2545;color:white;padding:10px 14px;text-align:left;}}
  td {{padding:8px 14px;border-bottom:1px solid #E2E8F0;}}
  tr:nth-child(even){{background:#F8FAFC;}}
  .badge {{display:inline-block;padding:4px 12px;border-radius:4px;
            color:white;font-weight:bold;background:{z_color};}}
  .kpi-grid {{display:grid;grid-template-columns:repeat(3,1fr);gap:16px;margin:16px 0;}}
  .kpi-card {{background:#F1F5F9;border-left:4px solid #0D9488;
              padding:16px;border-radius:4px;}}
  .kpi-val {{font-size:24px;font-weight:bold;color:#0B2545;}}
  .kpi-label {{font-size:12px;color:#64748B;margin-top:4px;}}
</style></head><body>
<h1>Financial Analytics Report — {company_id}</h1>
<p style="color:#64748B">Period: {years[0] if years else 'N/A'} | FinIntel Platform v2.0</p>

<h2>Key Financial Metrics</h2>
<div class="kpi-grid">
  <div class="kpi-card">
    <div class="kpi-val">{to_cr(rev.get("value"))} Cr</div>
    <div class="kpi-label">Revenue  YoY: {fmt(rev.get("yoy"), True)}</div>
  </div>
  <div class="kpi-card">
    <div class="kpi-val">{to_cr(ebd.get("value"))} Cr</div>
    <div class="kpi-label">EBITDA  Margin: {fmt(ebd.get("margin"), True)}</div>
  </div>
  <div class="kpi-card">
    <div class="kpi-val">{to_cr(pat.get("value"))} Cr</div>
    <div class="kpi-label">PAT  Margin: {fmt(pat.get("margin"), True)}</div>
  </div>
  <div class="kpi-card">
    <div class="kpi-val">{to_cr(kpis.get("total_assets", {}).get("value"))} Cr</div>
    <div class="kpi-label">Total Assets</div>
  </div>
  <div class="kpi-card">
    <div class="kpi-val">{kpis.get("current_ratio", {}).get("value") or "—"}</div>
    <div class="kpi-label">Current Ratio</div>
  </div>
  <div class="kpi-card" style="border-left-color:{z_color}">
    <div class="kpi-val" style="color:{z_color}">{z_disp}</div>
    <div class="kpi-label">Altman Z  <span class="badge">{(z.get("zone") or "").upper()}</span></div>
  </div>
</div>

<h2>Cost Structure (INR Cr)</h2>
<table>
  <tr><th>Cost Item</th><th>Value (INR Cr)</th><th>% of Revenue</th></tr>
  {cost_rows_html}
</table>
<p style="color:#94A3B8;font-size:11px;margin-top:40px">FinIntel Financial Analytics Platform v2.0 — Confidential</p>
</body></html>"""
